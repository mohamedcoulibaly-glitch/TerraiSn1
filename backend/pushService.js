const fs = require('fs');
const path = require('path');
const webpush = require('web-push');
const { getDb, queryAll, queryOne, runSql } = require('./database');
const logger = require('./logger');

let configured = false;
let autoGenerated = false;

function vapidStorePath() {
  const dbPath = process.env.DB_PATH
    ? path.resolve(process.env.DB_PATH)
    : path.resolve(__dirname, 'terrainsn.db');
  return path.join(path.dirname(dbPath), 'vapid-keys.json');
}

function loadPersistedVapid() {
  try {
    const file = vapidStorePath();
    if (!fs.existsSync(file)) return null;
    const raw = JSON.parse(fs.readFileSync(file, 'utf8'));
    if (raw?.publicKey && raw?.privateKey) return raw;
  } catch {
    /* ignore */
  }
  return null;
}

function persistVapid(keys) {
  try {
    const file = vapidStorePath();
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(
      file,
      JSON.stringify(
        {
          publicKey: keys.publicKey,
          privateKey: keys.privateKey,
          subject: keys.subject || process.env.VAPID_SUBJECT || 'mailto:contact@terrainsn.com',
          generatedAt: new Date().toISOString(),
        },
        null,
        2,
      ),
      'utf8',
    );
    return true;
  } catch (err) {
    logger.warn('pushService', `Impossible de persister VAPID : ${err.message}`);
    return false;
  }
}

/**
 * Résout les clés VAPID : env → fichier à côté de la DB → génération auto (persistée).
 * Sur Render free sans disque, la génération se répète à chaque machine neuve
 * (les abonnements push devront être re-souscrits) — préférer les env vars.
 */
function resolveVapidKeys() {
  let publicKey = String(process.env.VAPID_PUBLIC_KEY || '').trim();
  let privateKey = String(process.env.VAPID_PRIVATE_KEY || '').trim();
  const subject = process.env.VAPID_SUBJECT || 'mailto:contact@terrainsn.com';

  if (publicKey && privateKey) {
    return { publicKey, privateKey, subject, source: 'env' };
  }

  const stored = loadPersistedVapid();
  if (stored) {
    process.env.VAPID_PUBLIC_KEY = stored.publicKey;
    process.env.VAPID_PRIVATE_KEY = stored.privateKey;
    if (stored.subject && !process.env.VAPID_SUBJECT) {
      process.env.VAPID_SUBJECT = stored.subject;
    }
    return {
      publicKey: stored.publicKey,
      privateKey: stored.privateKey,
      subject: stored.subject || subject,
      source: 'file',
    };
  }

  const generated = webpush.generateVAPIDKeys();
  process.env.VAPID_PUBLIC_KEY = generated.publicKey;
  process.env.VAPID_PRIVATE_KEY = generated.privateKey;
  const persisted = persistVapid({ ...generated, subject });
  autoGenerated = true;
  logger.warn(
    'pushService',
    persisted
      ? 'VAPID auto-générées et persistées près de la DB — ajoutez-les en env Render pour stabilité multi-machine'
      : 'VAPID auto-générées en mémoire seule — les push seront invalidés au redémarrage',
  );
  return {
    publicKey: generated.publicKey,
    privateKey: generated.privateKey,
    subject,
    source: persisted ? 'generated-persisted' : 'generated-memory',
  };
}

function getVapidConfig() {
  const keys = resolveVapidKeys();
  return {
    publicKey: keys.publicKey || '',
    privateKey: keys.privateKey || '',
    subject: keys.subject || 'mailto:contact@terrainsn.com',
    source: keys.source,
    autoGenerated,
  };
}

function ensureConfigured() {
  if (configured) return true;
  const { publicKey, privateKey, subject } = getVapidConfig();
  if (!publicKey || !privateKey) {
    logger.warn('pushService', 'VAPID keys manquantes — Web Push desactivé');
    return false;
  }
  webpush.setVapidDetails(subject, publicKey, privateKey);
  configured = true;
  return true;
}

function getPublicKey() {
  ensureConfigured();
  return getVapidConfig().publicKey || null;
}

function describe() {
  const cfg = getVapidConfig();
  const ok = Boolean(cfg.publicKey && cfg.privateKey);
  return {
    configured: ok,
    source: cfg.source || null,
    autoGenerated,
    subject: cfg.subject,
    readyForProd: ok && (cfg.source === 'env' || cfg.source === 'file'),
  };
}

/**
 * Régénère une paire VAPID (superadmin) : persiste près de la DB, met à jour process.env
 * et invalide les abonnements existants (ils ne sont plus valides avec la nouvelle clé).
 * Attention : si VAPID_* est défini côté hébergeur (env Render…), il faut aussi y reporter la nouvelle clé.
 */
async function regenerateVapidKeys() {
  const subject = process.env.VAPID_SUBJECT || 'mailto:contact@terrainsn.com';
  const generated = webpush.generateVAPIDKeys();
  process.env.VAPID_PUBLIC_KEY = generated.publicKey;
  process.env.VAPID_PRIVATE_KEY = generated.privateKey;
  const persisted = persistVapid({ ...generated, subject });
  autoGenerated = true;
  configured = false;
  ensureConfigured();

  let abonnementsInvalides = 0;
  try {
    const db = await getDb();
    const row = queryOne(db, 'SELECT COUNT(*) AS n FROM push_subscriptions');
    abonnementsInvalides = Number(row?.n || 0);
    runSql(db, 'DELETE FROM push_subscriptions');
  } catch (err) {
    logger.warn('pushService', `Purge abonnements après régénération VAPID : ${err.message}`);
  }

  return {
    publicKey: generated.publicKey,
    subject,
    persisted,
    abonnements_invalides: abonnementsInvalides,
    warning: 'Si VAPID_PUBLIC_KEY / VAPID_PRIVATE_KEY sont définis dans l\'environnement d\'hébergement, mets-les à jour (sinon l\'ancienne clé reviendra au redémarrage).',
  };
}

/** Journalise un envoi push (best-effort, ne bloque jamais l'envoi). */
async function logPush({ userId, accountType = 'user', type, titre, corps, data = null, statut = 'envoye', erreur = null }) {
  try {
    const db = await getDb();
    runSql(
      db,
      `INSERT INTO push_logs (user_id, account_type, type_notif, titre, corps, data, statut, erreur)
       VALUES (?, ?, ?, ?, ?, ?, ?, ?)`,
      [
        userId != null ? Number(userId) : null,
        accountType,
        String(type || 'generic'),
        String(titre || '').slice(0, 255),
        String(corps || '').slice(0, 1000),
        data ? JSON.stringify(data) : null,
        statut,
        erreur ? String(erreur).slice(0, 500) : null,
      ],
    );
  } catch (err) {
    logger.warn('pushService', `push_logs : ${err.message}`);
  }
}

/** Liste filtrée des envois push (superadmin). */
async function listPushLogs({ userId, type, statut, depuis, jusqua, limit } = {}) {
  const db = await getDb();
  const where = [];
  const params = [];
  if (userId != null && userId !== '') {
    where.push('user_id = ?');
    params.push(Number(userId));
  }
  if (type) {
    where.push('type_notif = ?');
    params.push(String(type));
  }
  if (statut) {
    where.push('statut = ?');
    params.push(String(statut));
  }
  if (depuis) {
    where.push('created_at >= ?');
    params.push(String(depuis));
  }
  if (jusqua) {
    where.push('created_at <= ?');
    params.push(String(jusqua));
  }
  const max = Math.min(Math.max(Number(limit) || 100, 1), 500);
  const rows = queryAll(
    db,
    `SELECT * FROM push_logs ${where.length ? `WHERE ${where.join(' AND ')}` : ''}
     ORDER BY created_at DESC, id DESC LIMIT ${max}`,
    params,
  );
  return rows.map((row) => {
    let data = null;
    try {
      data = row.data ? JSON.parse(row.data) : null;
    } catch {
      data = row.data;
    }
    return { ...row, data };
  });
}

async function upsertSubscription(userId, subscription, userAgent = '') {
  ensureConfigured();
  const db = await getDb();
  const { endpoint, keys } = subscription;
  if (!endpoint || !keys?.p256dh || !keys?.auth) {
    throw new Error('Subscription Web Push invalide');
  }

  runSql(db, `INSERT INTO push_subscriptions (user_id, endpoint, p256dh, auth, user_agent)
    VALUES (?, ?, ?, ?, ?)
    ON CONFLICT(endpoint) DO UPDATE SET
      user_id = excluded.user_id,
      p256dh = excluded.p256dh,
      auth = excluded.auth,
      user_agent = excluded.user_agent`, [
    userId,
    endpoint,
    keys.p256dh,
    keys.auth,
    userAgent.slice(0, 255),
  ]);

  runSql(db, `INSERT OR IGNORE INTO push_preferences (user_id) VALUES (?)`, [userId]);
}

async function removeSubscription(userId, endpoint) {
  const db = await getDb();
  runSql(db, 'DELETE FROM push_subscriptions WHERE user_id = ? AND endpoint = ?', [userId, endpoint]);
}

async function getPreferences(userId) {
  const db = await getDb();
  const prefs = queryOne(db, 'SELECT * FROM push_preferences WHERE user_id = ?', [userId]);
  if (!prefs) {
    return {
      reservation_confirmation: true,
      rappel_reservation: true,
      promotion: false,
      nouveau_message: true,
      avis_reponse: true,
    };
  }
  return {
    reservation_confirmation: !!prefs.reservation_confirmation,
    rappel_reservation: !!prefs.rappel_reservation,
    promotion: !!prefs.promotion,
    nouveau_message: !!prefs.nouveau_message,
    avis_reponse: !!prefs.avis_reponse,
  };
}

async function updatePreferences(userId, prefs) {
  const db = await getDb();
  runSql(db, `INSERT INTO push_preferences (user_id, reservation_confirmation, rappel_reservation, promotion, nouveau_message, avis_reponse)
    VALUES (?, ?, ?, ?, ?, ?)
    ON CONFLICT(user_id) DO UPDATE SET
      reservation_confirmation = excluded.reservation_confirmation,
      rappel_reservation = excluded.rappel_reservation,
      promotion = excluded.promotion,
      nouveau_message = excluded.nouveau_message,
      avis_reponse = excluded.avis_reponse`, [
    userId,
    prefs.reservation_confirmation ? 1 : 0,
    prefs.rappel_reservation ? 1 : 0,
    prefs.promotion ? 1 : 0,
    prefs.nouveau_message ? 1 : 0,
    prefs.avis_reponse ? 1 : 0,
  ]);
  return getPreferences(userId);
}

async function getSubscriptionsForUser(userId) {
  const db = await getDb();
  return queryAll(db, 'SELECT * FROM push_subscriptions WHERE user_id = ?', [userId]);
}

async function sendToUser(userId, payload, preferenceKey = null) {
  if (!ensureConfigured()) return { sent: 0, failed: 0 };

  if (preferenceKey) {
    const prefs = await getPreferences(userId);
    if (!prefs[preferenceKey]) return { sent: 0, failed: 0, skipped: true };
  }

  const subscriptions = await getSubscriptionsForUser(userId);
  let sent = 0;
  let failed = 0;

  for (const sub of subscriptions) {
    try {
      await webpush.sendNotification(
        {
          endpoint: sub.endpoint,
          keys: { p256dh: sub.p256dh, auth: sub.auth },
        },
        JSON.stringify(payload),
      );
      sent++;
    } catch (err) {
      failed++;
      if (err.statusCode === 404 || err.statusCode === 410) {
        const db = await getDb();
        runSql(db, 'DELETE FROM push_subscriptions WHERE id = ?', [sub.id]);
      }
      logger.error('pushService', `Envoi push echoue (user ${userId})`, err);
    }
  }

  if (sent > 0 || failed > 0) {
    await logPush({
      userId,
      type: payload?.type || preferenceKey || 'generic',
      titre: payload?.title,
      corps: payload?.body,
      data: payload?.url ? { url: payload.url, tag: payload.tag } : null,
      statut: sent > 0 ? 'envoye' : 'echec',
      erreur: failed > 0 ? `${failed} abonnement(s) en échec` : null,
    });
  }

  return { sent, failed };
}

async function envoyerConfirmationPush(reservationId) {
  const db = await getDb();
  const reservation = queryOne(db, `SELECT r.*, t.nom AS terrain_nom
    FROM reservations r JOIN terrains t ON t.id = r.terrain_id WHERE r.id = ?`, [reservationId]);
  if (!reservation?.joueur_id) return;

  await sendToUser(reservation.joueur_id, {
    title: 'Réservation confirmée ⚽',
    body: `${reservation.terrain_nom} — ${reservation.date} à ${reservation.heure_debut}. Code : ${reservation.code_reservation || 'N/A'}`,
    url: '/reservations',
    tag: `reservation-${reservationId}`,
    type: 'reservation_confirmation',
  }, 'reservation_confirmation');

  runSql(db, `INSERT INTO notifications (destinataire_type, destinataire_id, type, canal, contenu, lu)
    VALUES ('user', ?, 'confirmation', 'push', ?, 0)`, [
    reservation.joueur_id,
    `Réservation confirmée : ${reservation.terrain_nom} le ${reservation.date} à ${reservation.heure_debut}`,
  ]);
}

async function envoyerRappelsReservations() {
  const db = await getDb();
  const now = new Date();
  const pushReady = ensureConfigured();
  const { parseReservationDateTime, isInReminderWindow } = require('./services/reminderWindow');
  const notificationService = require('./notificationService');

  const reservations = queryAll(db, `
    SELECT r.*, t.nom AS terrain_nom
    FROM reservations r
    JOIN terrains t ON t.id = r.terrain_id
    LEFT JOIN reservation_reminders rr ON rr.reservation_id = r.id
    WHERE r.statut IN ('confirme', 'acceptee')
      AND rr.id IS NULL
      AND r.date >= date('now')
  `);

  let processed = 0;
  let pushCount = 0;
  let waCount = 0;

  for (const reservation of reservations) {
    const startAt = parseReservationDateTime(reservation.date, reservation.heure_debut);
    if (!isInReminderWindow(startAt, now)) continue;

    let pushSent = false;
    let waSent = false;

    if (pushReady && reservation.joueur_id) {
      const prefs = await getPreferences(reservation.joueur_id);
      if (prefs.rappel_reservation) {
        const result = await sendToUser(reservation.joueur_id, {
          title: 'Rappel — match dans 1h ⏰',
          body: `${reservation.terrain_nom} — ${reservation.date} à ${reservation.heure_debut}. Préparez-vous !`,
          url: '/reservations',
          tag: `reminder-${reservation.id}`,
          type: 'rappel_reservation',
        }, 'rappel_reservation');
        pushSent = result.sent > 0;
      }
    }

    try {
      const wa = await notificationService.envoyerRappelReservation(reservation.id);
      waSent = Boolean(wa && (wa.ok || wa.mocked) && !wa.skipped);
    } catch (err) {
      logger.warn('pushService', `Rappel WhatsApp #${reservation.id} : ${err.message}`);
    }

    if (!pushSent && !waSent) continue;

    runSql(db, 'INSERT INTO reservation_reminders (reservation_id) VALUES (?)', [reservation.id]);
    if (reservation.joueur_id) {
      const canal = pushSent && waSent ? 'push+whatsapp' : pushSent ? 'push' : 'whatsapp';
      runSql(db, `INSERT INTO notifications (destinataire_type, destinataire_id, type, canal, contenu, lu)
        VALUES ('user', ?, 'rappel', ?, ?, 0)`, [
        reservation.joueur_id,
        canal,
        `Rappel : match au ${reservation.terrain_nom} dans 1h`,
      ]);
    }
    if (pushSent) pushCount += 1;
    if (waSent) waCount += 1;
    processed += 1;
    logger.event('rappel_match', { reservation_id: reservation.id, push: pushSent, whatsapp: waSent });
  }

  return { processed, push: pushCount, whatsapp: waCount };
}

